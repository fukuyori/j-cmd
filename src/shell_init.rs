pub fn generate(args: &[String]) -> Result<String, String> {
    let shell = args
        .first()
        .ok_or_else(|| "Usage: j init <zsh|bash|powershell> [--cmd j|cd]".to_string())?;
    let mut command = "j";
    let mut index = 1;
    while index < args.len() {
        match args[index].as_str() {
            "--cmd" => {
                command = args
                    .get(index + 1)
                    .map(String::as_str)
                    .ok_or_else(|| "--cmd requires j or cd".to_string())?;
                if command != "j" && command != "cd" {
                    return Err("--cmd must be j or cd".to_string());
                }
                index += 2;
            }
            option => return Err(format!("Unknown init option: {option}")),
        }
    }

    match shell.to_ascii_lowercase().as_str() {
        "zsh" => Ok(generate_zsh(command == "cd")),
        "bash" => Ok(generate_bash(command == "cd")),
        "powershell" | "pwsh" => Ok(generate_powershell(command == "cd")),
        _ => Err(format!("Unsupported shell: {shell}")),
    }
}

fn generate_zsh(replace_cd: bool) -> String {
    let command_definition = if replace_cd {
        r#"cd() {
    if (( $# == 0 )); then
        builtin cd
        return
    fi
    if __j_is_direct_command "$1"; then
        command j "$@"
        return
    fi
    if builtin cd "$@" 2>/dev/null; then
        return
    fi
    __j_jump "$@"
}
j() { cd "$@"; }
ji() { cd -i "$@"; }"#
    } else {
        r#"j() { __j_dispatch "$@"; }
ji() { __j_jump -i "$@"; }"#
    };
    let completion_targets = if replace_cd { "j cd" } else { "j" };
    ZSH_TEMPLATE
        .replace("__J_COMMAND_DEFINITION__", command_definition)
        .replace("__J_COMPLETION_TARGETS__", completion_targets)
}

fn generate_bash(replace_cd: bool) -> String {
    let command_definition = if replace_cd {
        r#"cd() {
    if (( $# == 0 )); then
        builtin cd
        return
    fi
    if __j_is_direct_command "$1"; then
        command j "$@"
        return
    fi
    if builtin cd "$@" 2>/dev/null; then
        return
    fi
    __j_jump "$@"
}
j() { cd "$@"; }
ji() { cd -i "$@"; }"#
    } else {
        r#"j() { __j_dispatch "$@"; }
ji() { __j_jump -i "$@"; }"#
    };
    let completion_targets = if replace_cd { "j cd" } else { "j" };
    BASH_TEMPLATE
        .replace("__J_COMMAND_DEFINITION__", command_definition)
        .replace("__J_COMPLETION_TARGETS__", completion_targets)
}

fn generate_powershell(replace_cd: bool) -> String {
    let command_definition = if replace_cd {
        r#"Remove-Item Alias:cd -Force -ErrorAction SilentlyContinue
function global:cd {
    if ($args.Count -eq 0) {
        Set-Location
        return
    }
    if ($args.Count -eq 1 -and
        (Test-Path -LiteralPath $args[0] -PathType Container -ErrorAction SilentlyContinue)) {
        Set-Location -LiteralPath $args[0]
        & $global:__j_cmd_binary -c 2>$null
        $global:__j_cmd_last_pwd = (Get-Location).ProviderPath
        return
    }
    Invoke-JCmd -CommandArgs $args
}
function global:j { cd @args }
function global:ji { Invoke-JCmdJump -JumpArgs (@("-i") + $args) }"#
    } else {
        r#"function global:j { Invoke-JCmd -CommandArgs $args }
function global:ji { Invoke-JCmdJump -JumpArgs (@("-i") + $args) }"#
    };
    let completion_targets = if replace_cd { "j,ji,cd" } else { "j,ji" };
    let binary_name = if cfg!(windows) { "j.exe" } else { "j" };
    POWERSHELL_TEMPLATE
        .replace("__J_COMMAND_DEFINITION__", command_definition)
        .replace("__J_COMPLETION_TARGETS__", completion_targets)
        .replace("__J_BINARY__", binary_name)
}

const ZSH_TEMPLATE: &str = r#"# Generated by j init zsh. Run compinit before evaluating this script.
__j_is_direct_command() {
    case "$1" in
        init|-c|-x|-xa|-a|-ar|-al|-h|--help|-V|--version|--complete|--exclude-add|--exclude-remove|--exclude-list|--ranking|--fzf-opts|--fzf-opts-clear)
            return 0
            ;;
    esac
    return 1
}

__j_dispatch() {
    if (( $# > 0 )) && __j_is_direct_command "$1"; then
        command j "$@"
    else
        __j_jump "$@"
    fi
}

__j_jump() {
    local result
    result="$(command j "$@")"
    if [[ -d "$result" ]]; then
        __j_skip_record=1
        builtin cd -- "$result"
    elif [[ -n "$result" ]]; then
        print -u2 -- "$result"
    fi
}

__J_COMMAND_DEFINITION__

autoload -Uz add-zsh-hook
__j_record_pwd() {
    if (( __j_skip_record )); then
        __j_skip_record=0
    else
        command j -c >/dev/null 2>&1
    fi
}
add-zsh-hook chpwd __j_record_pwd

_j_generated_complete() {
    if [[ "${words[2]}" == "init" ]]; then
        if (( CURRENT == 3 )); then
            _values 'shell' zsh bash powershell
        elif [[ "${words[CURRENT-1]}" == "--cmd" ]]; then
            _values 'command' j cd
        else
            _values 'init option' '--cmd[replace command name]'
        fi
        return
    fi
    if [[ "${words[CURRENT-1]}" == "--ranking" ]]; then
        _values 'ranking' recent frecency frequency
        return
    fi
    if (( CURRENT == 2 )) && [[ "${words[CURRENT]}" == -* ]]; then
        _values 'option' -i -l -c -x -xa --ranking --fzf-opts --fzf-opts-clear
        return
    fi
    local keyword="${words[2,-1]}"
    local -a candidates
    candidates=("${(@f)$(command j --complete "$keyword" 2>/dev/null)}")
    if (( ${#candidates[@]} )); then
        compadd -a candidates
    else
        _files -/
    fi
}

if (( $+functions[compdef] )); then
    compdef _j_generated_complete __J_COMPLETION_TARGETS__
fi
"#;

const BASH_TEMPLATE: &str = r#"# Generated by j init bash.
__j_is_direct_command() {
    case "$1" in
        init|-c|-x|-xa|-a|-ar|-al|-h|--help|-V|--version|--complete|--exclude-add|--exclude-remove|--exclude-list|--ranking|--fzf-opts|--fzf-opts-clear)
            return 0
            ;;
    esac
    return 1
}

__j_dispatch() {
    if (( $# > 0 )) && __j_is_direct_command "$1"; then
        command j "$@"
    else
        __j_jump "$@"
    fi
}

__j_jump() {
    local result
    result="$(command j "$@")"
    if [[ -d "$result" ]]; then
        builtin cd -- "$result"
        __j_last_pwd="$PWD"
    elif [[ -n "$result" ]]; then
        printf '%s\n' "$result" >&2
    fi
}

__J_COMMAND_DEFINITION__

__j_last_pwd="$PWD"
__j_record_pwd() {
    if [[ "$PWD" != "$__j_last_pwd" ]]; then
        command j -c >/dev/null 2>&1
        __j_last_pwd="$PWD"
    fi
}
case ";${PROMPT_COMMAND:-};" in
    *";__j_record_pwd;"*) ;;
    *) PROMPT_COMMAND="__j_record_pwd${PROMPT_COMMAND:+;$PROMPT_COMMAND}" ;;
esac

_j_generated_complete() {
    local current="${COMP_WORDS[COMP_CWORD]}"
    local previous="${COMP_WORDS[COMP_CWORD-1]}"
    if [[ "${COMP_WORDS[1]}" == "init" ]]; then
        if [[ "$previous" == "init" ]]; then
            COMPREPLY=($(compgen -W "zsh bash powershell" -- "$current"))
        elif [[ "$previous" == "--cmd" ]]; then
            COMPREPLY=($(compgen -W "j cd" -- "$current"))
        fi
        return
    fi
    if [[ "$previous" == "--ranking" ]]; then
        COMPREPLY=($(compgen -W "recent frecency frequency" -- "$current"))
        return
    fi
    if [[ "$current" == -* ]]; then
        COMPREPLY=($(compgen -W "-i --interactive -l --list -c -x -xa -a -ar -al -h --help -V --version --ranking --fzf-opts --fzf-opts-clear --exclude-add --exclude-remove --exclude-list" -- "$current"))
        return
    fi
    local keyword="${COMP_WORDS[*]:1}"
    local candidates
    candidates="$(command j --complete "$keyword" 2>/dev/null)"
    COMPREPLY=($(compgen -W "$candidates" -- "${COMP_WORDS[COMP_CWORD]}"))
}
complete -F _j_generated_complete __J_COMPLETION_TARGETS__
"#;

const POWERSHELL_TEMPLATE: &str = r#"# Generated by j init powershell.
$global:__j_cmd_binary = (
    Get-Command __J_BINARY__ -CommandType Application -ErrorAction Stop |
        Select-Object -First 1
).Source

function global:Invoke-JCmdJump {
    param([object[]]$JumpArgs)
    $result = & $global:__j_cmd_binary @JumpArgs
    $output = "$result".Trim()
    if ($output -and
        (Test-Path -LiteralPath $output -PathType Container -ErrorAction SilentlyContinue)) {
        Set-Location -LiteralPath $output
        $global:__j_cmd_last_pwd = (Get-Location).ProviderPath
    } elseif ($output) {
        Write-Host $output -ForegroundColor Yellow
    }
}

function global:Invoke-JCmd {
    param([object[]]$CommandArgs)
    $directCommands = @(
        "init", "-c", "-x", "-xa", "-a", "-ar", "-al",
        "-h", "--help", "-V", "--version", "--complete",
        "--exclude-add", "--exclude-remove", "--exclude-list",
        "--ranking", "--fzf-opts", "--fzf-opts-clear"
    )
    if ($CommandArgs.Count -gt 0 -and $directCommands -contains [string]$CommandArgs[0]) {
        & $global:__j_cmd_binary @CommandArgs
    } else {
        Invoke-JCmdJump -JumpArgs $CommandArgs
    }
}

__J_COMMAND_DEFINITION__

if (-not $global:__j_cmd_prompt_hooked) {
    $global:__j_cmd_original_prompt = $function:prompt
    $global:__j_cmd_last_pwd = (Get-Location).ProviderPath
    function global:prompt {
        $jCmdLastExitCode = $global:LASTEXITCODE
        $jCmdCurrentPwd = (Get-Location).ProviderPath
        if ($jCmdCurrentPwd -ne $global:__j_cmd_last_pwd) {
            & $global:__j_cmd_binary -c 2>$null | Out-Null
            $global:__j_cmd_last_pwd = $jCmdCurrentPwd
        }
        $global:LASTEXITCODE = $jCmdLastExitCode
        if ($global:__j_cmd_original_prompt) {
            & $global:__j_cmd_original_prompt
        } else {
            "PS $($executionContext.SessionState.Path.CurrentLocation)> "
        }
    }
    $global:__j_cmd_prompt_hooked = $true
}

Register-ArgumentCompleter -CommandName __J_COMPLETION_TARGETS__ -ScriptBlock {
    param($commandName, $parameterName, $wordToComplete, $commandAst)
    $line = $commandAst.ToString()
    $values = @()
    if ($line -match '(^|\s)init(\s+\S*)?$') {
        $values = @("zsh", "bash", "powershell", "--cmd")
    } elseif ($line -match '(^|\s)--cmd(\s+\S*)?$') {
        $values = @("j", "cd")
    } elseif ($line -match '(^|\s)--ranking(\s+\S*)?$') {
        $values = @("recent", "frecency", "frequency")
    } elseif ($wordToComplete.StartsWith("-")) {
        $values = @(
            "-i", "--interactive", "-l", "--list", "-c", "-x", "-xa",
            "-a", "-ar", "-al", "-h", "--help", "-V", "--version",
            "--ranking", "--fzf-opts", "--fzf-opts-clear",
            "--exclude-add", "--exclude-remove", "--exclude-list"
        )
    }
    if ($values.Count -gt 0) {
        $values | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
            [System.Management.Automation.CompletionResult]::new(
                $_, $_, [System.Management.Automation.CompletionResultType]::ParameterValue, $_
            )
        }
        return
    }
    & $global:__j_cmd_binary --complete $wordToComplete 2>$null | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new(
            $_, $_, [System.Management.Automation.CompletionResultType]::ParameterValue, $_
        )
    }
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn zsh_init_defaults_to_j_without_replacing_cd() {
        let script = generate(&["zsh".to_string()]).unwrap();
        assert!(script.contains("j() { __j_dispatch"));
        assert!(!script.contains("cd() {"));
        assert!(script.contains("init|-c|-x"));
        assert!(script.contains("compdef _j_generated_complete j"));
    }

    #[test]
    fn bash_init_can_replace_cd() {
        let script =
            generate(&["bash".to_string(), "--cmd".to_string(), "cd".to_string()]).unwrap();
        assert!(script.contains("cd() {"));
        assert!(script.contains("complete -F _j_generated_complete j cd"));
    }

    #[test]
    fn powershell_init_contains_wrapper_and_completion() {
        let script = generate(&["powershell".to_string()]).unwrap();
        assert!(script.contains("function global:j"));
        assert!(script.contains("function global:Invoke-JCmd"));
        assert!(script.contains("__j_cmd_prompt_hooked"));
        assert!(script.contains("Register-ArgumentCompleter -CommandName j,ji"));
    }

    #[test]
    fn powershell_cd_mode_removes_the_cd_alias() {
        let script = generate(&[
            "powershell".to_string(),
            "--cmd".to_string(),
            "cd".to_string(),
        ])
        .unwrap();
        assert!(script.contains("Remove-Item Alias:cd"));
        assert!(script.contains("function global:cd"));
    }

    #[test]
    fn init_rejects_unknown_command_name() {
        let error =
            generate(&["zsh".to_string(), "--cmd".to_string(), "jump".to_string()]).unwrap_err();
        assert_eq!(error, "--cmd must be j or cd");
    }
}
